/**
 * Retrieve regional crop diagnosis by crop name and target language
 *
 * @param {string} cropName Raw crop name (e.g. "Wheat/गेहूं", "Tomato")
 * @param {string} symptoms Farmer notes / symptoms
 * @param {string} season Current agricultural season
 * @param {string} language Target language code (e.g. "pa", "mr", "gu", "ta", "te", "kn", "bn", "hi", "en")
 * @returns {Object} Complete localized diagnostic report
 */
function getCropDiagnosis(cropName, symptoms, season, language = 'hi') {
  // Normalize language to 2-letter code
  const rawLang = String(language || 'hi').toLowerCase().trim();
  const langKey = rawLang.split('-')[0].split('_')[0];
  const activeLang = CROP_DATA[langKey] ? langKey : 'hi';

  const langProfiles = CROP_DATA[activeLang];
  const normCrop = String(cropName || '').toLowerCase().trim();

  // Find matching crop key
  const cropKeys = ['wheat', 'rice', 'tomato', 'potato', 'cotton', 'onion', 'sugarcane', 'maize', 'soybean'];
  const matchedKey = cropKeys.find((k) => normCrop.includes(k)) || 'other';

  const profile = langProfiles[matchedKey] || langProfiles.other;

  // Language metadata mapping
  const langCodes = {
    hi: 'hi-IN',
    pa: 'pa-guru-IN',
    mr: 'mr-IN',
    gu: 'gu-IN',
    ta: 'ta-IN',
    te: 'te-IN',
    kn: 'kn-IN',
    bn: 'bn-IN',
    en: 'en-IN',
  };

  const langNames = {
    hi: 'Hindi',
    pa: 'Punjabi',
    mr: 'Marathi',
    gu: 'Gujarati',
    ta: 'Tamil',
    te: 'Telugu',
    kn: 'Kannada',
    bn: 'Bengali',
    en: 'English',
  };

  const disclaimer = REGIONAL_DISCLAIMERS[activeLang] || REGIONAL_DISCLAIMERS.hi;

  return {
    crop: profile.crop,
    possibleIssue: profile.possibleIssue,
    confidence: profile.confidence,
    severity: profile.severity,
    observations: [...profile.observations],
    recommendedActions: [...profile.recommendedActions],
    expertAttention: profile.expertAttention,
    additionalNotes: profile.additionalNotes,
    imageQuality: 'good',
    language: langCodes[activeLang] || 'hi-IN',
    languageCode2: activeLang,
    languageName: langNames[activeLang] || 'Hindi',
    disclaimer,
  };
}

